import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const root=new URL('../',import.meta.url);
const html=fs.readFileSync(new URL('index.html',root),'utf8');
const helper=fs.readFileSync(new URL('scripts/cod_notice.js',root),'utf8');
function extract(name){const text=html.match(new RegExp('(?:async )?function '+name+'\\([^)]*\\)\\{[\\s\\S]*?\\n\\}'))?.[0];assert.ok(text,name);return text}
const node={hidden:true,innerHTML:'',textContent:''};
let method='Contra entrega',resolve,calls=0;
const context=vm.createContext({$:(id)=>id==='checkoutCodNotice'?node:null,selectedPayment:()=>method,sb:{rpc:async(name)=>{assert.equal(name,'get_public_storefront_cod_notice');calls++;return await new Promise(r=>resolve=r)}}});
vm.runInContext(helper,context);
const notice={success:true,enabled:true,title:'Condiciones <script>',body:'Primer párrafo\r\nSegunda línea\r\n\r\n- Punto <img src=x onerror=alert(1)>\n- Símbolo 🎁'};
const normalized=context.CODNotice.normalize(notice);
assert.equal(normalized.body.includes('\r'),false);
const markup=context.CODNotice.render(normalized);
assert.ok(markup.includes('<ul><li>Punto &lt;img'));
assert.ok(markup.includes('Primer párrafo<br>Segunda línea'));
assert.ok(markup.includes('&lt;script&gt;'));
assert.ok(!markup.includes('<script>')&&!markup.includes('<img'));
assert.doesNotThrow(()=>context.CODNotice.normalize({...notice,title:'🎁'.repeat(120),body:'🎁'.repeat(3000)}));
for(const invalid of [null,{}, {...notice,success:false},{...notice,enabled:1},{...notice,title:null},{...notice,body:[]},{...notice,title:'🎁'.repeat(121)},{...notice,body:'x'.repeat(3001)},{...notice,title:'x\n'},{...notice,body:'x\u0001'},{...notice,title:' '},{...notice,body:'\n\t '}])assert.throws(()=>context.CODNotice.normalize(invalid));
for(const space of ['\u00a0','\u1680','\u2003','\u2028','\u2029','\u202f','\u205f','\u3000','\ufeff']){
 assert.throws(()=>context.CODNotice.normalize({...notice,title:space}));
 assert.throws(()=>context.CODNotice.normalize({...notice,body:space}));
 assert.equal(context.CODNotice.normalize({...notice,title:space+'Título'+space}).title,'Título');
}
assert.doesNotThrow(()=>context.CODNotice.normalize({success:true,enabled:false,title:'',body:''}));
vm.runInContext('let storefrontCodNotice=null,storefrontCodNoticePromise=null,storefrontCodNoticeRefreshPending=false;\n'+['renderStorefrontCodNotice','refreshStorefrontCodNotice'].map(extract).join('\n'),context);
context.renderStorefrontCodNotice();assert.equal(node.hidden,true);
const first=context.refreshStorefrontCodNotice(),duplicate=context.refreshStorefrontCodNotice();
assert.equal(calls,1,'Requests en curso se comparten');assert.equal(node.hidden,true);
resolve({data:notice,error:null});assert.equal(await first,true);assert.equal(await duplicate,true);
assert.equal(node.hidden,false);assert.ok(node.innerHTML.includes('&lt;img'));
method='PSE';context.renderStorefrontCodNotice();assert.equal(node.hidden,true);assert.equal(node.textContent,'');
method='Contra entrega';
const disabled=context.refreshStorefrontCodNotice();resolve({data:{success:true,enabled:false,title:'',body:''},error:null});assert.equal(await disabled,true);assert.equal(node.hidden,true);
const failed=context.refreshStorefrontCodNotice();resolve({data:null,error:{code:'PGRST202'}});assert.equal(await failed,false);assert.equal(node.hidden,true);assert.equal(method,'Contra entrega','Error de copy no cambia el medio de pago');
const bad=context.refreshStorefrontCodNotice();resolve({data:{success:true,enabled:true,title:'x',body:null},error:null});assert.equal(await bad,false);assert.equal(node.hidden,true);
const pending=context.refreshStorefrontCodNotice();method='Tarjeta';resolve({data:notice,error:null});await pending;assert.equal(node.hidden,true,'Respuesta tardía respeta selección actual');
method='Contra entrega';
const before=calls,older=context.refreshStorefrontCodNotice(),finishOlder=resolve;
const force=context.refreshStorefrontCodNotice(true),anotherForce=context.refreshStorefrontCodNotice(true);
finishOlder({data:{...notice,title:'Copy viejo'},error:null});
await older;await force;await anotherForce;
assert.equal(calls,before+2,'Varias notificaciones encolan una sola lectura nueva');
assert.equal(node.hidden,true,'La respuesta anterior no se muestra después de una notificación');
const latest=context.refreshStorefrontCodNotice();resolve({data:{...notice,title:'Copy nuevo'},error:null});await latest;
assert.equal(node.hidden,false);assert.ok(node.innerHTML.includes('Copy nuevo')&&!node.innerHTML.includes('Copy viejo'));
assert.ok(html.includes('<script src="scripts/cod_notice.js"></script>'));
assert.ok(html.includes('id="checkoutCodNotice"')&&html.includes('aria-label="Información adicional de contraentrega"'));
for(const opener of ['detailBuyNow','sendCart'])assert.ok(extract(opener).includes('refreshStorefrontCodNotice()'),opener+' recarga copy');
assert.ok(html.includes("if(type==='cod-notice-changed'){void refreshStorefrontCodNotice(true);return}"));
for(const name of ['confirmCheckout','saveContraEntregaOrder','payWithWompi'])assert.ok(!extract(name).includes('storefrontCodNotice'),name+' independiente de copy');
console.log('PASS cod_notice_regression: texto plano/Unicode/XSS, párrafos/listas, visibilidad COD, fallos y refresco encolado sin copy stale.');
